function setMissing(target, dotted, value) {
	const parts = dotted.split(".")
	let cur = target
	for (let i = 0; i < parts.length - 1; i++) {
		const k = parts[i]
		if (!(k in cur)) {
			cur[k] = {}
		} else if (typeof cur[k] !== "object" || cur[k] === null || Array.isArray(cur[k])) {
			return // existing non-object blocks this path; skip
		}
		cur = cur[k]
	}
	const last = parts[parts.length - 1]
	if (!(last in cur)) cur[last] = value
}

function applyArea(relDir, file, table) {
	for (const lc of LOCALES) {
		const fp = path.join(ROOT, relDir, lc, file)
		let obj
		try {
			obj = JSON.parse(fs.readFileSync(fp, "utf8"))
		} catch (e) {
			console.warn(`skip missing file: ${fp}`)
			continue
		}
		const idx = LOCALES.indexOf(lc)
		let added = 0
		for (const dotted in table) {
			const before = JSON.stringify(obj)
			setMissing(obj, dotted, table[dotted][idx])
			if (JSON.stringify(obj) !== before) added++
		}
		fs.writeFileSync(fp, JSON.stringify(obj, null, "\t") + "\n")
		console.log(`${relDir}/${lc}/${file}: +${added}`)
	}
}

